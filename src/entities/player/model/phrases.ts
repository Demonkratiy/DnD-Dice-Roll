/**
 * Реплики персонажа во время броска — «эмоции» по классам.
 *
 * Это доменные данные: чистые, сериализуемые, без React. Для каждого класса —
 * свой набор фраз для двух моментов броска:
 *   - `shake`  — пока игрок зажал и трясёт кубики;
 *   - `release` — после отпускания, пока крутится анимация расчёта.
 *
 * Если класс не выбран, используется нейтральный набор `DEFAULT_PHRASES`.
 * Сам выбор конкретной фразы (случайный) делается в UI-слое — здесь только данные.
 */

import type { PlayerClassId } from './classes.ts'

/** Пара наборов реплик для одного класса. */
export interface ClassPhrases {
  /** Фразы в момент тряски (зажатие). */
  shake: readonly string[]
  /** Фразы в момент броска (отпускание, крутятся кубики). */
  release: readonly string[]
}

/** Нейтральный набор — когда класс героя не выбран. */
export const DEFAULT_PHRASES: ClassPhrases = {
  shake: ['Трясём кубики…', 'Встряхиваем кости в ладонях…', 'Разогреваем кубики тряской…'],
  release: ['Кубики крутятся… ну же…', 'Катятся, ждём результат…', 'Замерли в предвкушении…'],
}


/**
 * Сущность «бросок» (roll): запрос на бросок, его исход и итоговое событие.
 *
 * Все типы СЕРИАЛИЗУЕМЫ — это сознательное ограничение ради задела под мультиплеер:
 * бросок должен быть самодостаточным объектом, который можно сохранить или
 * передать по сети без потери смысла.
 */

import type { DieType } from '@entities/die'
import type { Player } from '@entities/player'

/**
 * Режим броска.
 * - `normal` — обычный бросок;
 * - `advantage` — преимущество (бросаем дважды, берём больший результат);
 * - `disadvantage` — помеха (бросаем дважды, берём меньший результат).
 *
 * Advantage/disadvantage по правилам D&D применяется к d20, но механика
 * реализована обобщённо (бросить дважды и выбрать) и работает для любой кости.
 */
export type RollMode = 'normal' | 'advantage' | 'disadvantage'

/** Запрос на бросок: что именно кидаем. */
export interface RollRequest {
  /** Номинал кубика (например, d20). */
  die: DieType
  /** Сколько кубиков данного номинала бросаем (например, 3 для 3d6). */
  count: number
  /** Модификатор, прибавляемый к сумме (может быть отрицательным). */
  modifier: number
  /** Режим броска. */
  mode: RollMode
}

/** Результат одной кости. */
export interface DieRoll {
  /** Номинал кости. */
  die: DieType
  /** Выпавшее значение в диапазоне [1, число граней]. */
  value: number
}

/**
 * Чистый исход броска: что выпало и сколько вышло в сумме.
 * Не содержит метаданных события (id/время/автор) — это вычислимая,
 * детерминированная (при фиксированном RNG) часть.
 */
export interface RollOutcome {
  /** Учитываемые кости (их значения идут в сумму). */
  dice: DieRoll[]
  /**
   * Отброшенные кости — например, проигравший бросок при advantage/disadvantage.
   * Хранятся для прозрачности и красивого отображения в логе.
   */
  dropped: DieRoll[]
  /** Модификатор, применённый к сумме. */
  modifier: number
  /** Итог: сумма значений учитываемых костей плюс модификатор. */
  total: number
}

/**
 * Итоговое событие броска — то, что попадает в лог и (в будущем) пересылается
 * по сети. Объединяет исход с метаданными: кто, когда и по какому запросу бросил.
 */
export interface RollResult extends RollOutcome {
  /** Уникальный идентификатор события. */
  id: string
  /** Исходный запрос. */
  request: RollRequest
  /** Автор броска. */
  author: Player
  /** Метка времени (мс с эпохи Unix). */
  timestamp: number
}

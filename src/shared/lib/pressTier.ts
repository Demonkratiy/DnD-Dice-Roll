/**
 * pressTier — дискретные «тиры» силы зажатия поверх непрерывной интенсивности.
 *
 * Жест (usePressAndShake) копит непрерывную intensity 0..1 за время удержания.
 * Для «эмоций» броска полезно различать три качественных режима:
 *  - normal  — обычный тап/короткое зажатие;
 *  - charged — заметно «заряженный» бросок (свечение уже подросло);
 *  - epic    — особо сильное зажатие: максимум драмы (усиленное свечение,
 *              более долгое вращение, в перспективе — отдельные эпик-реплики).
 *
 * Это чистая функция без React/DOM: её одинаково используют живой визуал сцены
 * (по текущей intensity) и оркестратор броска (по интенсивности отпускания).
 */

export type PressTier = 'normal' | 'charged' | 'epic'

/** Порог входа в «заряженный» режим (доля удержания 0..1).
 * При MAX_PRESS_MS = 3000 это 1 секунда удержания (1/3 пути до максимума). */
export const CHARGED_PRESS_INTENSITY = 1 / 3
/** Порог входа в «эпический» режим — нужно держать до максимума.
 * При MAX_PRESS_MS = 3000 это 3 секунды удержания. Переход 2→3 фазы (2 c) —
 * вдвое длиннее перехода 1→2 (1 c). */
export const EPIC_PRESS_INTENSITY = 1

/** Возвращает тир зажатия по текущей интенсивности 0..1. */
export function getPressTier(intensity: number): PressTier {
  if (intensity >= EPIC_PRESS_INTENSITY) return 'epic'
  if (intensity >= CHARGED_PRESS_INTENSITY) return 'charged'
  return 'normal'
}

/**
 * spinReveal — единый источник правды для смены номинала у вращающейся цифры.
 *
 * Цифра крутится вместе с силуэтом (`rotateY(--die-rot)`) и НЕ прячет «изнанку» —
 * зеркаленье на задней половине просто читается как часть вращения. Задача helper:
 * сказать, КАКОЕ число показывать при данном угле, так чтобы:
 *  1) число менялось РОВНО раз на видимый оборот, и
 *  2) сама подмена приходилась на самый незаметный кадр.
 *
 * Тонкость «видимого оборота». Силуэты кубика симметричны, и под `rotateY` форма
 * на 180° выглядит как завершённый оборот (та же фигура, лишь зеркально). Поэтому
 * зритель воспринимает ОДИН оборот за 180°, а не за 360°. Если менять число каждые
 * 360°, оно «висит» два видимых оборота — отсюда ощущение рассинхрона. Значит
 * период смены = 180°.
 *
 * Где менять. На «ребре» (θ ≈ 90° / 270°) грань перпендикулярна зрителю
 * (`cos θ ≈ 0`), её ширина → 0 и цифра почти не видна. Меняем значение именно там:
 * к «лицу» (0° / 180°) силуэт приходит уже с новым числом, которое «вырастает из
 * ребра» — без заметного щелчка на стыке.
 */

/** Градусов в одном полном обороте `rotateY`. */
export const SPIN_PER_TURN = 360

/**
 * Период смены номинала (градусы). Половина оборота: для симметричного силуэта это
 * один ВИДИМЫЙ оборот. Меньший период → число меняется чаще, чем кубик «делает
 * оборот»; больший (360°) → число висит два видимых оборота.
 */
export const SPIN_SWAP_PERIOD = SPIN_PER_TURN / 2 // 180

/**
 * Фаза свопа (градусы) — сдвиг момента смены на «ребро» (90°, 270°, 450°…), где
 * грань перпендикулярна зрителю и цифра почти не видна. Так подмена незаметна, а
 * новое число доворачивается к лицу уже целиком.
 */
export const SPIN_SWAP_PHASE = SPIN_PER_TURN / 4 // 90

/**
 * Максимальный прирост угла за кадр (градусы). Меньше половины периода свопа —
 * тогда один кадр не способен «перепрыгнуть» целую смену, и число гарантированно
 * меняется ровно по разу на каждом ребре, без пропусков на быстром обороте.
 */
export const MAX_SPIN_STEP = SPIN_SWAP_PERIOD / 2 - 10 // 80

/**
 * Индекс смены — какое по счёту число показывать. Растёт на каждом ребре
 * (90°, 270°, 450°…). Зависит ТОЛЬКО от накопленного угла, без состояния-счётчика,
 * — это устойчиво к скачкам кадров: даже если угол перепрыгнул границу, индекс
 * посчитается верно.
 */
export const spinRevealIndex = (spin: number): number =>
  Math.floor((spin + SPIN_SWAP_PHASE) / SPIN_SWAP_PERIOD)

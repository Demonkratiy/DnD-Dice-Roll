/**
 * RNG (Random Number Generator — генератор случайных чисел) как инъектируемая
 * зависимость.
 *
 * Доменная логика НИКОГДА не вызывает `Math.random()` напрямую — она принимает
 * объект `Rng`. Это даёт:
 *  - тестируемость (в тестах подставляем детерминированный генератор);
 *  - задел под мультиплеер (в будущем сервер/ГМ сможет задать seed, чтобы у всех
 *    игроков совпали и анимация, и результат).
 */

/** Источник случайности. `next()` возвращает число в диапазоне [0, 1). */
export interface Rng {
  next(): number
}

/** Стандартная реализация на основе `Math.random()`. */
export function createMathRandomRng(): Rng {
  return {
    next: () => Math.random(),
  }
}

/**
 * Криптостойкая реализация на основе `crypto.getRandomValues`.
 *
 * Зачем нужна:
 *  - **непредсказуемость** — в отличие от `Math.random()`, исход нельзя угадать,
 *    зная предыдущие значения. Это важно под честный мультиплеер (см. ниже);
 *  - **качественная энтропия** — биты приходят из системного CSPRNG.
 *
 * `next()` даёт [0, 1) из 32 случайных бит (этого с запасом хватает для кубиков:
 * остаточный modulo bias при раскладке на грани имеет порядок 2^-32 и неощутим).
 *
 * Если `crypto` недоступен (очень старое окружение) — откатываемся на Math.random.
 *
 * TODO (мультиплеер): seedable-генератор (детерминируемый по seed) пока СОЗНАТЕЛЬНО
 * не добавляем. Он нужен только в модели, где клиенты сами вычисляют бросок из
 * общего зерна (P2P / без авторитетного сервера). При архитектуре «авторитетный
 * сервер шлёт готовый RollResult» seed не требуется — хватает crypto на сервере.
 * Окончательно решаем при переходе на мультиплеер. См. dev-wiki/rolling-domain.md.
 */
export function createCryptoRng(): Rng {
  const cryptoObj = typeof crypto !== 'undefined' && 'getRandomValues' in crypto ? crypto : null
  if (!cryptoObj) {
    return createMathRandomRng()
  }

  const buffer = new Uint32Array(1)
  const nextUint32 = () => {
    cryptoObj.getRandomValues(buffer)
    return buffer[0]
  }

  return {
    // Делим на 2^32 → равномерное [0, 1).
    next: () => nextUint32() / 0x1_0000_0000,
  }
}

/**
 * Бросок одной кости с заданным числом граней: целое в диапазоне [1, sides].
 * Вынесено отдельно, чтобы единообразно использовать во всей доменной логике.
 */
export function rollSingleDie(rng: Rng, sides: number): number {
  return Math.floor(rng.next() * sides) + 1
}

/** Режим «заряженного» кубика для DEV-тестов: всегда максимум или минимум. */
export type LoadedRollMode = 'max' | 'min'

/**
 * DEV-only «заряженный» RNG: всегда даёт максимум или минимум грани.
 * Нужен, чтобы тестировать крит-эффекты (нат-20 / нат-1) без перебора десятков
 * честных бросков. Подменяется на шве RollSource, поэтому доменный `rollDice`
 * и крит-логика остаются нетронутыми: кость честно «выпадает» 20/1.
 *
 * `next ≈ 0.999999` → floor(next * sides) + 1 = sides (максимум для любой грани,
 * включая d100, т.к. 0.999999 > 1 − 1/100); `next = 0` → 1 (минимум).
 */
export function createLoadedRng(mode: LoadedRollMode): Rng {
  return { next: () => (mode === 'max' ? 0.999999 : 0) }
}

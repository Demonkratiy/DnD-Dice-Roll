/**
 * SoundPlayer — абстракция звукового сопровождения.
 *
 * Звуки в MVP не реализованы, но архитектурный «шов» заложен заранее: ключевые
 * точки анимации броска (старт тряски, фиксация, показ результата, крит) будут
 * вызывать методы этого интерфейса. Сейчас используется тихая заглушка
 * `NoopSoundPlayer`, позже её заменит реализация на Web Audio / `<audio>`.
 */

/** Идентификаторы звуковых событий приложения. */
export type SoundEvent = 'shakeStart' | 'settle' | 'reveal' | 'crit'

/** Проигрыватель звуков. */
export interface SoundPlayer {
  play(event: SoundEvent): void
}

/** Заглушка: ничего не воспроизводит. Используется, пока звуки не реализованы. */
export const noopSoundPlayer: SoundPlayer = {
  play: () => {
    /* намеренно ничего не делаем — задел под будущую реализацию */
  },
}
